// рисунок — bones.ts. Снимок — одна или две проекции на плёнке: запястье и голеностоп — в прямой и
// боковой, стопа — в прямой, тазобедренный сустав, ключица и рёбра — в прямой. Координаты панели —
// в долях её ширины по обеим осям (y — вниз), панель на плёнке — сдвиг и масштаб.
//
// Кость — контур через опорные точки, корковые полосы вдоль диафиза, линии замыкательных пластинок
// и балок. Рисовальщик болезней не знает: перелом задан местом и смещением. Линия перелома делит
// кость на неподвижный и смещённый отломок; со смещённым уходят кости, которые за ним следуют
// (при переломе лучевой кости — запястье и кисть). Что перелом значит, запишут признаки базы по
// источникам (часть 32).
