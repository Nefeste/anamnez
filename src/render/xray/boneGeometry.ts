const clamp01 = (x: number | undefined) => (x === undefined || !Number.isFinite(x) ? 0 : Math.min(1, Math.max(0, x)));

function bone(id: string, pts: readonly Pt[], o: Partial<Omit<Bone, 'id' | 'outline'>> & { n?: number } = {}): Bone {
  return { id, outline: closedSpline(pts, o.n ?? 6), holes: o.holes ?? [], walls: o.walls ?? [], lines: o.lines ?? [], density: o.density ?? 1 };
}

/** Кость чуть крупнее или мельче вокруг середины: суставные щели запястья и предплюсны — узкие. */
function grow(b: Bone, k: number): Bone {
  const [cx, cy] = [b.outline.reduce((a, p) => a + p[0], 0) / b.outline.length, b.outline.reduce((a, p) => a + p[1], 0) / b.outline.length];
  const f = (pts: Pt[]) => pts.map(([x, y]) => [cx + (x - cx) * k, cy + (y - cy) * k] as Pt);
  return { ...b, outline: f(b.outline), lines: b.lines.map(l => ({ ...l, pts: f(l.pts) })) };
}

/**
 * Трубчатая кость по оси от основания к головке: полуширина в опорных точках, скруглённая головка,
 * почти плоское основание; корковые полосы — вдоль диафиза (доли длины `shaft`).
 */
function longBone(id: string, center: readonly Pt[], half: readonly number[], o: { density?: number; shaft?: [number, number]; cortex?: number; base?: number; head?: number } = {}): Bone {
  const c = openSpline(center, 6);
  const hw = c.map((_, i) => {
    const s = (i / (c.length - 1)) * (half.length - 1);
    const k = Math.min(half.length - 2, Math.floor(s));
    return half[k] + (half[k + 1] - half[k]) * (s - k);
  });
  const left: Pt[] = [], right: Pt[] = [];
  const dirs: Pt[] = c.map((p, i) => {
    const a = c[Math.max(0, i - 1)], b = c[Math.min(c.length - 1, i + 1)];
    const dx = b[0] - a[0], dy = b[1] - a[1];
    const l = Math.hypot(dx, dy) || 1;
    return [dx / l, dy / l];
  });
  c.forEach((p, i) => {
    const [ax, ay] = dirs[i];
    left.push([p[0] - ay * hw[i], p[1] + ax * hw[i]]);
    right.push([p[0] + ay * hw[i], p[1] - ax * hw[i]]);
  });
  // концы — дуги: головка — полукруг, основание — приплюснутая дуга
  const cap = (p: Pt, dir: Pt, r: number, bulge: number, from: 'left' | 'right'): Pt[] => {
    const [ax, ay] = dir;
    const nx = from === 'left' ? -ay : ay, ny = from === 'left' ? ax : -ax;
    return Array.from({ length: 9 }, (_, k) => {
      const t = (Math.PI * (k + 1)) / 10;
      return [p[0] + nx * r * Math.cos(t) + ax * bulge * Math.sin(t), p[1] + ny * r * Math.cos(t) + ay * bulge * Math.sin(t)] as Pt;
    });
  };
  const last = c.length - 1;
  const headCap = cap(c[last], dirs[last], hw[last], hw[last] * (o.head ?? 0.9), 'left');
  const [bx, by] = dirs[0];
  const baseCap = cap(c[0], [-bx, -by], hw[0], hw[0] * (o.base ?? 0.3), 'right');
  const outline = [...left, ...headCap, ...right.reverse(), ...baseCap];
  const [s0, s1] = o.shaft ?? [0.25, 0.8];
  const i0 = Math.round(s0 * last), i1 = Math.round(s1 * last);
  const t = o.cortex ?? 0.3;
  const walls = [
    strip(left.slice(i0, i1 + 1), c, hw[i0] * t, hw[i1] * t, 0.25, false),
    strip(outline.slice(outline.length - baseCap.length - 1 - i1, outline.length - baseCap.length - i0), c, hw[i1] * t, hw[i0] * t, 0.25, false),
  ];
  return { id, outline, holes: [], walls, lines: [], density: o.density ?? 1 };
}

/** Замыкательная пластинка или балка — светлая линия через опорные точки. */
const plate = (pts: readonly Pt[], width = 0.006, alpha = 0.5): BoneLine => ({ pts: openSpline(pts, 5), width, alpha });

/** Перелом: линия поперёк оси, стороны для обрезки, смещение. */
function fracture(site: FractureSite, boneId: string, c: Pt, axis: Pt, span: number, oblique: number, move: Move, rng: Rng, gap = 0.007): FractureGeo {
  const jag = () => (rng.int(1000) / 1000 - 0.5) * 0.012;
  const line = fractureLine(c, axis, span, oblique, jag);
  const { fixed, moving } = sides(line, axis, gap);
  return { site, bone: boneId, line, fixed, moving, move };
}

