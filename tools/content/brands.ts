  'колдрекс', 'фервекс', 'амоксиклав', 'флемоксин', 'аугментин', 'сумамед', 'азитрал', 'лазолван', 'амбробене', 'ацц',
  'мукалтин', 'називин', 'отривин', 'аква марис', 'зиртек', 'кларитин', 'эриус', 'супрастин', 'тавегил', 'беродуал',
